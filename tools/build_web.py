"""Bundle the refmeta package for the browser converter (web/convert.html).

    python build_web.py           # write ../web/refmeta_bundle.js
    python build_web.py --check   # exit 1 if the bundle is out of date

The page runs this same refmeta package in Pyodide. A page opened from file://
cannot fetch files next to it, so the bundle is a script that sets
window.REFMETA_BUNDLE:

    files    {path: file text}  refmeta/**/*.py, refmeta/data/**, and the page's
                                Python glue (web/refmeta_web.py as refmeta_web.py).
                                The page writes these into Pyodide's filesystem
                                before `import refmeta`.
    samples  [{...}]            a few one-click example files from sources/*/examples
    version  short hash of everything above

refmeta/data/ is a copy of mapping/ (see sync_data.py). The build stops if that
copy is out of date, so the page never runs an old mapping.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
TASK = TOOLS.parent
PACKAGE = TOOLS / "refmeta"
SOURCES = TASK / "sources"
WEB = TASK / "web"
GLUE = WEB / "refmeta_web.py"
OUT = WEB / "refmeta_bundle.js"

DATA_SUFFIXES = (".json", ".yaml", ".yml")

# (button label, what it is, path under sources/). One per source.
SAMPLES = [
    ("NCBI assembly report", "Yeast R64, header plus sequence table",
     "ncbi/examples/ftp_GCF_000146045.2_R64_assembly_report.txt"),
    ("UCSC chrom.sizes", "sacCer3", "ucsc/examples/bigZips_sacCer3.chrom.sizes"),
    ("refgenie alias", "R64-1-1 from a refgenie server", "refgenie/examples/api_alias_R64-1-1.json"),
    ("FHR YAML", "R64-1-1 (constructed example)", "fhr/examples/constructed/R64-1-1.fhr.yaml"),
    ("seqcol level 2", "R64-1-1 sequence collection",
     "ga4gh/examples/seqcol_level2_R64-1-1_ia9g4Myony-xxLsSc7eQOC_NdClGgPGu.json"),
    ("Galaxy all_fasta.loc", "usegalaxy CVMFS, 6 rows", "galaxy/examples/cvmfs_all_fasta.loc"),
    ("Ensembl REST assembly", "Yeast, /info/assembly",
     "ensembl/examples/rest_info_assembly_saccharomyces_cerevisiae.json"),
    ("ENA sequence report", "GCA_000146045.2", "ena/examples/sequence_report_GCA_000146045.2.txt"),
    ("nf-core datasheet", "iGenomes UCSC sacCer3", "nfcore/examples/datasheet_igenomes_UCSC_sacCer3.yml"),
    ("Bioconductor Seqinfo", "sacCer3 (constructed example)",
     "bioconductor/examples/constructed/seqinfo_sacCer3.tsv"),
]


def package_files() -> dict[str, str]:
    """Bundle path -> text for the package, its data and the page glue."""
    files: dict[str, str] = {}
    for p in sorted(PACKAGE.rglob("*")):
        if not p.is_file() or "__pycache__" in p.parts:
            continue
        rel = p.relative_to(TOOLS).as_posix()
        if p.suffix == ".py" or (rel.startswith("refmeta/data/") and p.suffix in DATA_SUFFIXES):
            files[rel] = p.read_text(encoding="utf-8")
    files["refmeta_web.py"] = GLUE.read_text(encoding="utf-8")
    return files


def sample_entries() -> list[dict]:
    """The sample files, with the format their fields.json lists them under."""
    listed: dict[str, str] = {}
    for fj in sorted(SOURCES.glob("*/fields.json")):
        inv = json.loads(fj.read_text(encoding="utf-8"))
        for fm in inv["formats"]:
            if fm.get("adapter"):
                for ex in fm.get("example_files", []):
                    listed.setdefault(f"{fj.parent.name}/{ex}", fm["id"])
    out = []
    for name, about, rel in SAMPLES:
        path = SOURCES / rel
        if not path.is_file():
            raise SystemExit(f"build_web: sample file missing: sources/{rel}")
        out.append({
            "label": name, "about": about, "path": f"sources/{rel}", "filename": path.name,
            "source": rel.split("/", 1)[0], "format": listed.get(rel, ""),
            "text": path.read_text(encoding="utf-8"),
        })
    return out


def render(files: dict[str, str], samples: list[dict]) -> str:
    h = hashlib.sha256()
    for k, v in files.items():
        h.update(k.encode() + b"\0" + v.encode("utf-8") + b"\0")
    for s in samples:
        h.update(s["path"].encode() + b"\0" + s["text"].encode("utf-8") + b"\0")
    lines = [
        "/* refmeta browser bundle. Generated by tools/build_web.py; do not edit.",
        "   files: the refmeta package and its data (path -> file text); samples: example files. */",
        "window.REFMETA_BUNDLE = {",
        f'"version": {json.dumps(h.hexdigest()[:12])},',
        '"files": {',
        ",\n".join(f"{json.dumps(k)}: {json.dumps(v)}" for k, v in files.items()),
        "},",
        '"samples": [',
        ",\n".join(json.dumps(s, sort_keys=True) for s in samples),
        "]",
        "};",
    ]
    return "\n".join(lines) + "\n"


def data_is_current() -> bool:
    sys.path.insert(0, str(TOOLS))
    sys.dont_write_bytecode = True
    import sync_data  # noqa: E402  (same folder)

    write, delete = sync_data.stale(sync_data.planned())
    for p in write:
        print(f"build_web: out of date: {p.relative_to(TOOLS)}", file=sys.stderr)
    for p in delete:
        print(f"build_web: not in mapping/: {p.relative_to(TOOLS)}", file=sys.stderr)
    return not (write or delete)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="only report whether the bundle is current")
    ap.add_argument("--allow-stale-data", action="store_true",
                    help="build even if refmeta/data/ differs from mapping/ (run sync_data.py instead)")
    args = ap.parse_args(argv)
    if not data_is_current() and not args.allow_stale_data:
        print("build_web: refmeta/data/ is out of date; run `python sync_data.py` first", file=sys.stderr)
        return 1
    files, samples = package_files(), sample_entries()
    text = render(files, samples)
    if args.check:
        current = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        if not current:
            print(f"build_web: {OUT.relative_to(TASK)} is out of date", file=sys.stderr)
        return 0 if current else 1
    OUT.write_text(text, encoding="utf-8")
    size = OUT.stat().st_size
    print(f"build_web: wrote {OUT.relative_to(TASK)} ({size / 1024:.0f} KB): "
          f"{len(files)} files, {len(samples)} samples")
    return 0


if __name__ == "__main__":
    sys.exit(main())
